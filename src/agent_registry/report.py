"""Per agent KPIs from spans, OPA data export, and the monthly governance report."""
from __future__ import annotations

import json
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

from .core import EVAL_MAX_AGE_DAYS, Finding, load_jsonl, load_csv


def _p95(values: list[int]) -> int:
    if not values:
        return 0
    s = sorted(values)
    return s[min(len(s) - 1, int(round(0.95 * (len(s) - 1))))]


def agent_kpis(spans_path: Path, cost_path: Path, records: list[dict]) -> dict[str, dict]:
    """Join spans (keyed by gen_ai.agent.id) and cost lines (keyed by the Application tag) to registry IDs."""
    grouped: dict[str, list[dict]] = defaultdict(list)
    for s in load_jsonl(spans_path):
        grouped[s.get("gen_ai.agent.id") or "<untagged>"].append(s)

    app_to_agent = {r["cost_tags"]["Application"]: r["agent_id"] for r in records}
    cost = defaultdict(float)
    for row in load_csv(cost_path):
        aid = app_to_agent.get(row["Application"])
        if aid:
            cost[aid] += float(row["cost_usd"])

    out = {}
    for aid, spans in grouped.items():
        n = len(spans)
        out[aid] = {
            "invocations": n,
            "error_rate": sum(1 for s in spans if s["status"] == "ERROR") / n,
            "p95_ms": _p95([s["duration_ms"] for s in spans]),
            "guardrail_block_rate": sum(1 for s in spans if s.get("guardrail.action") == "blocked") / n,
            "tokens": sum(s["gen_ai.usage.input_tokens"] + s["gen_ai.usage.output_tokens"] for s in spans),
            "cost_usd": cost.get(aid),
        }
    return out


def opa_data(records: list[dict]) -> dict:
    """The slice of the registry the gateway policy needs. Published to the policy engine as data."""
    return {
        "agents": {
            r["agent_id"]: {
                "status": r["status"],
                "risk_tier": r["risk_tier"],
                "environment": r["environment"],
                "eval_result": r["evaluation"]["result"],
                "eval_last_run": r["evaluation"]["last_run"],
                "eval_max_age_days": EVAL_MAX_AGE_DAYS[r["risk_tier"]],
                "data_classification": r["data_classification"],
                "allowed_routes": ["llm-default"],
            }
            for r in records
        }
    }


def _pct(n: int, d: int) -> str:
    return f"{(100 * n / d):.0f}%" if d else "n/a"


def render_report(records: list[dict], findings: list[Finding], kpis: dict[str, dict], as_of: date) -> str:
    total = len(records)
    status = Counter(r["status"] for r in records)
    tiers = Counter(r["risk_tier"] for r in records if r["status"] == "approved")
    platforms = Counter(r["platform"] for r in records)
    by_rule = Counter(f.rule for f in findings)
    by_sev = Counter(f.severity for f in findings)
    flagged = {f.subject for f in findings}

    active = [r for r in records if r["status"] == "approved"]
    orphan_ids = {f.subject for f in findings if f.rule.startswith("ORPHANED")}
    eval_bad = {f.subject for f in findings if f.rule in ("EVAL_STALE", "EVAL_FAILING")}
    review_bad = {f.subject for f in findings if f.rule == "REVIEW_OVERDUE"}
    unregistered = [f for f in findings if f.rule in ("UNREGISTERED_AGENT", "UNREGISTERED_CALLER")]
    open_exc = [(r["agent_id"], e) for r in records for e in r.get("exceptions", [])]

    lines: list[str] = []
    a = lines.append
    a(f"# AI Agent Governance Report, as of {as_of.isoformat()}")
    a("")
    a("Synthetic data. Generated by `agent-registry report`. Every number below is computed from the registry and the source extracts in `data/`.")
    a("")
    a("## Headline")
    a("")
    a("| Measure | Value |")
    a("|---|---|")
    a(f"| Registered agents | {total} ({status['approved']} approved, {status['suspended']} suspended, {status['retired']} retired, {status['draft'] + status['pending_approval']} in intake) |")
    a(f"| Approved agents by risk tier | high {tiers['high']}, medium {tiers['medium']}, low {tiers['low']} |")
    a(f"| Approved agents with an active business and technical owner | {_pct(len([r for r in active if r['agent_id'] not in orphan_ids]), len(active))} |")
    a(f"| Approved agents with a current, passing evaluation | {_pct(len([r for r in active if r['agent_id'] not in eval_bad]), len(active))} |")
    a(f"| Approved agents with review up to date | {_pct(len([r for r in active if r['agent_id'] not in review_bad]), len(active))} |")
    a(f"| Unregistered agents or callers discovered | {len(unregistered)} |")
    a(f"| Exceptions on record | {len(open_exc)}, of which expired {by_rule['EXCEPTION_EXPIRED']} |")
    a(f"| Findings by severity | critical {by_sev['critical']}, high {by_sev['high']}, medium {by_sev['medium']}, low {by_sev['low']} |")
    a("")
    a("## Inventory by platform")
    a("")
    a("| Platform | Agents |")
    a("|---|---|")
    for p, n in sorted(platforms.items()):
        a(f"| {p} | {n} |")
    a("")
    a("## Findings requiring action")
    a("")
    a("| Severity | Rule | Subject | Detail | Action |")
    a("|---|---|---|---|---|")
    for f in findings:
        a(f"| {f.severity} | {f.rule} | {f.subject} | {f.detail} | {f.action} |")
    a("")
    a("## Runtime behavior by agent (last 30 days)")
    a("")
    a("Joined on `gen_ai.agent.id` (spans) and the `Application` cost tag. Thresholds are illustrative.")
    a("")
    a("| Agent | Tier | Invocations | Error rate | p95 latency | Guardrail blocks | Tokens | Cloud cost |")
    a("|---|---|---|---|---|---|---|---|")
    tier_of = {r["agent_id"]: r["risk_tier"] for r in records}
    for aid in sorted(kpis):
        k = kpis[aid]
        cost = f"${k['cost_usd']:,.0f}" if k["cost_usd"] is not None else "outside cloud bill"
        err = f"{100 * k['error_rate']:.1f}%" + (" (over 3%)" if k["error_rate"] > 0.03 else "")
        a(f"| {aid} | {tier_of.get(aid, '?')} | {k['invocations']:,} | {err} | {k['p95_ms']:,} ms | {100 * k['guardrail_block_rate']:.2f}% | {k['tokens']:,} | {cost} |")
    silent = [r["agent_id"] for r in active if r["agent_id"] not in kpis]
    if silent:
        a("")
        a(f"Approved agents with no telemetry this period: {', '.join(silent)}. No telemetry means no oversight; these need instrumentation or retirement.")
    a("")
    a("## Clean agents")
    a("")
    clean = [r["agent_id"] for r in records if r["agent_id"] not in flagged]
    a(", ".join(clean) if clean else "None this period.")
    a("")
    return "\n".join(lines)
